usage() {
  cat <<'USAGE'
Usage:
  scripts/verify_phase16_release.sh --source-gates
  scripts/verify_phase16_release.sh --release-gates --release-dir dist/releases/<release-id>
  scripts/verify_phase16_release.sh --publication-gates --target-ref <clean-publication-ref>

Options:
  --source-gates         Run full source verification before packaging.
  --release-gates        Verify a complete generated release artifact set.
  --release-dir <path>   Release directory generated by scripts/package_release.sh --verify.
  --publication-gates    Verify clean publication target tree hygiene.
  --target-ref <ref>     Clean publication branch or commit to inspect.
  --help, -h             Show this help.
USAGE
}

fail_usage() {
  printf 'error: %s\n' "$1" >&2
  usage >&2
  exit 64
}

set_mode() {
  local next_mode="$1"
  if [ -n "$MODE" ]; then
    fail_usage "exactly one mode is required"
  fi
  MODE="$next_mode"
}

require_value() {
  local option="$1"
  local value="${2:-}"
  if [ -z "$value" ]; then
    fail_usage "$option requires a value"
  fi
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --source-gates)
      set_mode "source"
      shift
      ;;
    --release-gates)
      set_mode "release"
      shift
      ;;
    --release-dir)
      require_value "$1" "${2:-}"
      RELEASE_DIR="$2"
      shift 2
      ;;
    --publication-gates)
      set_mode "publication"
      shift
      ;;
    --target-ref)
      require_value "$1" "${2:-}"
      TARGET_REF="$2"
      shift 2
      ;;
    --help|-h)
      usage
      exit 0
      ;;
    *)
      fail_usage "unknown option: $1"
      ;;
  esac
done

fail() {
  printf 'FAIL: %s\n' "$1" >&2
  failures=$((failures + 1))
}

pass() {
  printf 'PASS: %s\n' "$1"
}

require_file() {
  local path="$1"
  if [ -f "$path" ]; then
    pass "$path exists"
  else
    fail "$path is missing"
  fi
}

require_directory() {
  local path="$1"
  if [ -d "$path" ]; then
    pass "$path exists"
  else
    fail "$path is missing"
  fi
}

require_regular_file() {
  local path="$1"
  local description="$2"
  if [ -f "$path" ] && [ ! -L "$path" ]; then
    pass "$description"
  else
    fail "$description"
  fi
}

require_fixed_match() {
  local needle="$1"
  local path="$2"
  local description="$3"
  if grep -Fq -- "$needle" "$path"; then
    pass "$description"
  else
    fail "$description"
  fi
}

require_regex_absent() {
  local pattern="$1"
  local path="$2"
  local description="$3"
  local matches
  matches="$(grep -Eni -- "$pattern" "$path" || true)"
  if [ -n "$matches" ]; then
    printf 'Forbidden %s in %s:\n%s\n' "$description" "$path" "$matches" >&2
    fail "$description"
  else
    pass "$description"
  fi
}

require_command_pass() {
  local description="$1"
  shift
  if "$@"; then
    pass "$description"
  else
    fail "$description"
  fi
}

run_full_xctest_release_gate() {
  local xctestrun_matches=()
  local entitlements_matches=()
  local xctestrun_path
  local app_path
  local app_info_plist
  local entitlements_path

  xcodebuild build-for-testing \
    -project GlanceHold.xcodeproj \
    -scheme GlanceHold \
    -destination platform=macOS,arch=arm64 \
    -derivedDataPath "$XCODE_DERIVED_DATA" \
    -parallel-testing-enabled NO \
    -enableCodeCoverage NO || return 1

  shopt -s nullglob
  xctestrun_matches=("$XCODE_DERIVED_DATA"/Build/Products/*.xctestrun)
  entitlements_matches=("$XCODE_DERIVED_DATA"/Build/Intermediates.noindex/GlanceHold.build/Debug/GlanceHold.build/GlanceHold.app.xcent)
  shopt -u nullglob

  if [ "${#xctestrun_matches[@]}" -ne 1 ]; then
    printf 'Expected exactly one .xctestrun in %s/Build/Products, found %s\n' "$XCODE_DERIVED_DATA" "${#xctestrun_matches[@]}" >&2
    return 1
  fi
  xctestrun_path="${xctestrun_matches[0]}"

  app_path="$XCODE_DERIVED_DATA/Build/Products/Debug/GlanceHold.app"
  app_info_plist="$app_path/Contents/Info.plist"
  if [ ! -f "$app_info_plist" ]; then
    printf 'Expected built test host Info.plist at %s\n' "$app_info_plist" >&2
    return 1
  fi

  if [ "${#entitlements_matches[@]}" -ne 1 ]; then
    printf 'Expected exactly one test host entitlement file, found %s\n' "${#entitlements_matches[@]}" >&2
    return 1
  fi
  entitlements_path="${entitlements_matches[0]}"

  # The app must remain a menu-bar agent in production. For hosted CLI tests,
  # mutate only the temporary product so LaunchServices can launch and resume it.
  plutil -replace LSUIElement -bool NO "$app_info_plist" || return 1
  plutil -replace CFBundleIdentifier -string "$XCODE_TEST_HOST_BUNDLE_ID" "$app_info_plist" || return 1
  plutil -replace TestConfigurations.0.TestTargets.0.TestHostBundleIdentifier -string "$XCODE_TEST_HOST_BUNDLE_ID" "$xctestrun_path" || return 1
  plutil -replace TestConfigurations.0.TestTargets.0.BundleIdentifiersForCrashReportEmphasis.0 -string "$XCODE_TEST_HOST_BUNDLE_ID" "$xctestrun_path" || return 1
  plutil -replace TestConfigurations.0.TestTargets.0.ParallelizationEnabled -bool NO "$xctestrun_path" || return 1

  /usr/bin/codesign \
    --force \
    --sign - \
    --entitlements "$entitlements_path" \
    --timestamp=none \
    --generate-entitlement-der \
    "$app_path" || return 1

  "$LSREGISTER" -f -R -trusted "$app_path" || return 1
  /usr/bin/codesign --verify --deep --strict --verbose=2 "$app_path" || return 1

  xcodebuild test-without-building \
    -xctestrun "$xctestrun_path" \
    -destination platform=macOS,arch=arm64 \
    -derivedDataPath "$XCODE_DERIVED_DATA" \
    -parallel-testing-enabled NO \
    -enableCodeCoverage NO
}

extract_manifest_value() {
  local key="$1"
  local manifest_path="$2"
  local description="$3"
  manifest_value="$(plutil -extract "$key" raw "$manifest_path" 2>/dev/null || true)"
  if [ -n "$manifest_value" ]; then
    pass "$description"
  else
    fail "$description"
  fi
}

require_single_release_file() {
  local description="$1"
  local suffix="$2"
  local matches=()

  shopt -s nullglob
  case "$suffix" in
    dmg)
      matches=("$RELEASE_DIR"/*.dmg)
      ;;
    sha256)
      matches=("$RELEASE_DIR"/*.dmg.sha256)
      ;;
    manifest)
      matches=("$RELEASE_DIR"/*.manifest.json)
      ;;
    plugin)
      matches=("$RELEASE_DIR"/*.iinaplgz)
      ;;
  esac
  shopt -u nullglob

  single_release_path=""
  if [ "${#matches[@]}" -eq 1 ]; then
    single_release_path="${matches[0]}"
    pass "$description"
  else
    fail "$description"
  fi
}

