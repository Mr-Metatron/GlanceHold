    require_regex_absent 'signed and notarized' "$file" "signed and notarized overclaim"
    require_regex_absent 'Apple privacy review' "$file" "Apple privacy review overclaim"
    require_regex_absent 'no network communication' "$file" "no-network overclaim"
    require_regex_absent 'never uses network' "$file" "never-network overclaim"
    require_regex_absent 'supports[[:space:]]+VLC' "$file" "VLC support overclaim"
    require_regex_absent 'supports[[:space:]]+QuickTime' "$file" "QuickTime support overclaim"
    require_regex_absent 'supports[[:space:]]+browser video' "$file" "browser video support overclaim"
    require_regex_absent 'supports[[:space:]]+all players' "$file" "all-player support overclaim"
    require_regex_absent 'tracks your eyes' "$file" "eye-tracking overclaim"
    require_regex_absent 'knows where on the screen you are looking' "$file" "screen-gaze overclaim"
  done

  require_fixed_match "Camera frames are processed locally, not saved, and not uploaded." \
    "$README_FILE" "English README states local camera processing/not saved/not uploaded"
  require_fixed_match "local loopback bridge" \
    "$README_FILE" "English README discloses local loopback bridge"
  require_fixed_match "GlanceHold currently supports IINA." \
    "$README_FILE" "English README states IINA-only supported scope"
  require_fixed_match "Other players are not supported by the current release." \
    "$README_FILE" "English README states unsupported-player limits"
  require_fixed_match "Unsigned and not notarized; install requires macOS manual open / Open Anyway." \
    "$README_FILE" "English README states exact unsigned/manual-install sentence"
  require_fixed_match "Known limitations" \
    "$README_FILE" "English README has known limitations release-body field"

  require_fixed_match "摄像头画面会本地处理，不会保存，不会上传。" \
    "$README_ZH_FILE" "Chinese README states local camera processing/not saved/not uploaded"
  require_fixed_match "本地回环桥接" \
    "$README_ZH_FILE" "Chinese README discloses local loopback bridge"
  require_fixed_match "当前支持 IINA" \
    "$README_ZH_FILE" "Chinese README states IINA supported scope"
  require_fixed_match "当前 release 不支持其他播放器" \
    "$README_ZH_FILE" "Chinese README states unsupported-player limits"
  require_fixed_match "此版本未签名、未公证；安装需要通过 macOS 手动打开 / Open Anyway。" \
    "$README_ZH_FILE" "Chinese README states exact unsigned/manual-install meaning"
  require_fixed_match "已知限制" \
