  require_command_pass "Phase 11 MPV boundary verifier Bash syntax passes" \
    bash -n scripts/verify_phase11_mpv_boundary.sh
  require_command_pass "Phase 13 packaging verifier Bash syntax passes" \
    bash -n scripts/verify_phase13_packaging.sh
