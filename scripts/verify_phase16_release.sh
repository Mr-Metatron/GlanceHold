case "$MODE" in
  source)
    if [ -n "$RELEASE_DIR" ] || [ -n "$TARGET_REF" ]; then
      fail_usage "--source-gates does not accept --release-dir or --target-ref"
    fi
    run_source_gates
    ;;
  release)
    if [ -n "$TARGET_REF" ]; then
      fail_usage "--release-gates does not accept --target-ref"
    fi
    run_release_gates
    ;;
  publication)
    if [ -n "$RELEASE_DIR" ]; then
      fail_usage "--publication-gates does not accept --release-dir"
    fi
    run_publication_gates
    ;;
  *)
    fail_usage "one mode is required"
    ;;
esac

if [ "$failures" -eq 0 ]; then
  printf 'PASS: Phase 16 release verifier completed\n'
  exit 0
fi

printf 'FAIL: Phase 16 release verifier found %d failure(s)\n' "$failures" >&2
exit 1
