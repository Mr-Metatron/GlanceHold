  require_fixed_match "local single-user loopback integration" \
    "$PLUGIN_README_FILE" "plugin README discloses local loopback trust boundary"
  require_fixed_match "The current GlanceHold app/plugin pair uses this no-token local loopback trust model." \
    "$PLUGIN_README_FILE" "plugin README states local loopback release trust model"
  require_fixed_match "Speed Control and Pause/Resume playback behavior are verified by the release verification workflow." \
    "$PLUGIN_README_FILE" "plugin README keeps playback behavior in release verification scope"

  require_fixed_match "Unsigned and not notarized; install requires macOS manual open / Open Anyway." \
    "$RELEASE_PACKAGING_DOC" "release packaging docs state exact unsigned/manual-install sentence"
  require_fixed_match "complete release set" \
    "$RELEASE_PACKAGING_DOC" "release packaging docs require complete release set"
  require_fixed_match "known limitations" \
    "$RELEASE_PACKAGING_DOC" "release packaging docs keep known limitations in public release facts"

  require_fixed_match "Camera frames are processed locally on the Mac and are not saved or uploaded by GlanceHold." \
    "$RELEASE_BODY_TEMPLATE" "release body template states local camera processing/not saved/not uploaded"
  require_fixed_match "local loopback communication" \
    "$RELEASE_BODY_TEMPLATE" "release body template discloses local loopback"
  require_fixed_match "Current verified playback target is IINA with the matching GlanceHold Bridge plugin." \
    "$RELEASE_BODY_TEMPLATE" "release body template states IINA-only verified scope"
  require_fixed_match "Other players are not supported by this release." \
