run_release_gates() {
  local release_basename
  local dmg_path
  local sha_path
  local manifest_path
  local plugin_path
  local release_id
  local manifest_dmg_file_name
  local manifest_sha_file_name
  local manifest_sha
  local checksum_sha
  local actual_sha
  local source_git_dirty
  local source_git_sha
  local plugin_expected_asset
  local plugin_version
  local plugin_bridge_protocol_version
  local plugin_listing

  if [ -z "$RELEASE_DIR" ]; then
    fail_usage "--release-gates requires --release-dir"
  fi

  require_directory "$RELEASE_DIR"
  release_basename="$(basename "$RELEASE_DIR")"

  require_single_release_file "release set contains exactly one real DMG" "dmg"
  dmg_path="$single_release_path"
  require_single_release_file "release set contains exactly one .dmg.sha256 file" "sha256"
  sha_path="$single_release_path"
  require_single_release_file "release set contains exactly one .manifest.json file" "manifest"
  manifest_path="$single_release_path"
  require_single_release_file "release set contains exactly one .iinaplgz plugin package" "plugin"
  plugin_path="$single_release_path"

  if [ -n "$dmg_path" ]; then
    require_regular_file "$dmg_path" "DMG is a regular file"
  fi
  if [ -n "$sha_path" ]; then
    require_regular_file "$sha_path" ".dmg.sha256 is a regular file"
  fi
  if [ -n "$manifest_path" ]; then
    require_regular_file "$manifest_path" ".manifest.json is a regular file"
  fi
  if [ -n "$plugin_path" ]; then
    require_regular_file "$plugin_path" ".iinaplgz is a regular file"
  fi

  if [ -z "$dmg_path" ] || [ -z "$sha_path" ] || [ -z "$manifest_path" ] || [ -z "$plugin_path" ]; then
    run_public_claim_gates
    return
  fi

  extract_manifest_value "releaseId" "$manifest_path" "manifest exposes releaseId"
  release_id="$manifest_value"
  if [ "$release_id" = "$release_basename" ]; then
    pass "manifest releaseId matches release directory basename"
  else
    fail "manifest releaseId matches release directory basename"
  fi

  extract_manifest_value "artifact.dmgFileName" "$manifest_path" "manifest exposes artifact.dmgFileName"
  manifest_dmg_file_name="$manifest_value"
  extract_manifest_value "artifact.sha256FileName" "$manifest_path" "manifest exposes artifact.sha256FileName"
  manifest_sha_file_name="$manifest_value"
  manifest_sha="$(plutil -extract artifact.sha256 raw "$manifest_path" 2>/dev/null || true)"
  if [[ "$manifest_sha" =~ ^[0-9A-Fa-f]{64}$ ]]; then
    pass "manifest exposes artifact.sha256"
  else
    fail "manifest exposes artifact.sha256"
  fi

  if [ "$manifest_dmg_file_name" = "$(basename "$dmg_path")" ]; then
    pass "manifest DMG filename matches sibling DMG"
  else
    fail "manifest DMG filename matches sibling DMG"
  fi

  if [ "$manifest_sha_file_name" = "$(basename "$sha_path")" ]; then
    pass "manifest checksum filename matches sibling .dmg.sha256"
  else
    fail "manifest checksum filename matches sibling .dmg.sha256"
  fi

  checksum_sha="$(awk '{ print $1; exit }' "$sha_path")"
  actual_sha="$(shasum -a 256 "$dmg_path" | awk '{ print $1; exit }')"
  if [ "$manifest_sha" = "$checksum_sha" ] && [ "$manifest_sha" = "$actual_sha" ]; then
    pass "artifact.sha256 matches .dmg.sha256 and shasum output"
  else
    fail "artifact.sha256 matches .dmg.sha256 and shasum output"
  fi

  require_command_pass "hdiutil verify passes for generated DMG" \
    hdiutil verify "$dmg_path"

  plugin_expected_asset="$(plutil -extract plugin.expectedAssetName raw "$manifest_path" 2>/dev/null || true)"
  if [ "$plugin_expected_asset" = "$(basename "$plugin_path")" ]; then
    pass "plugin.expectedAssetName matches sibling .iinaplgz"
  else
    fail "plugin.expectedAssetName matches sibling .iinaplgz"
  fi

  if [[ "$plugin_expected_asset" =~ ^GlanceHoldBridge-.+-build-.+\.iinaplgz$ ]]; then
    pass "plugin.expectedAssetName uses release plugin package pattern"
  else
    fail "plugin.expectedAssetName uses release plugin package pattern"
  fi

  plugin_listing="$(zipinfo -1 "$plugin_path" 2>/dev/null || true)"
  if printf '%s\n' "$plugin_listing" | grep -Eq '(^|/)Info\.json$'; then
    pass ".iinaplgz contains Info.json"
  else
    fail ".iinaplgz contains Info.json"
  fi

  if printf '%s\n' "$plugin_listing" | grep -Eq '(^|/)main\.js$'; then
    pass ".iinaplgz contains main.js"
  else
    fail ".iinaplgz contains main.js"
  fi

  source_git_dirty="$(plutil -extract source.gitDirty raw "$manifest_path" 2>/dev/null || true)"
  if [ "$source_git_dirty" = "false" ] || [ "$source_git_dirty" = "0" ]; then
    pass "source.gitDirty=false in manifest"
  else
    fail "source.gitDirty=false in manifest"
  fi

  source_git_sha="$(plutil -extract source.gitSha raw "$manifest_path" 2>/dev/null || true)"
  if [ -n "$source_git_sha" ] && git cat-file -e "$source_git_sha^{commit}" 2>/dev/null; then
    pass "source.gitSha exists as a local commit"
  else
    fail "source.gitSha exists as a local commit"
  fi

  plugin_version="$(plutil -extract plugin.version raw "$manifest_path" 2>/dev/null || true)"
  if [ -n "$plugin_version" ]; then
    pass "manifest exposes plugin.version"
  else
    fail "manifest exposes plugin.version"
  fi

  plugin_bridge_protocol_version="$(plutil -extract plugin.bridgeProtocolVersion raw "$manifest_path" 2>/dev/null || true)"
  if [[ "$plugin_bridge_protocol_version" =~ ^[0-9]+$ ]]; then
    pass "manifest exposes numeric plugin.bridgeProtocolVersion"
  else
    fail "manifest exposes numeric plugin.bridgeProtocolVersion"
  fi

  run_public_claim_gates
}

run_publication_gates() {
  local target_commit
  local tree_paths
  local path
  local allowed

  if [ -z "$TARGET_REF" ]; then
    fail_usage "--publication-gates requires --target-ref"
  fi

  case "$TARGET_REF" in
    dev|refs/heads/dev|local/*|refs/heads/local/*)
      fail "publication target ref must not be dev or local/*"
      ;;
    *)
      pass "publication target ref is not a local-only branch name"
      ;;
  esac

  target_commit="$(git rev-parse --verify "$TARGET_REF^{commit}" 2>/dev/null || true)"
  if [ -n "$target_commit" ]; then
    pass "git rev-parse --verify target ref resolves to a commit"
  else
    fail "git rev-parse --verify target ref resolves to a commit"
    return
  fi

  tree_paths="$(git ls-tree -r --name-only "$target_commit")"
  while IFS= read -r path; do
    [ -n "$path" ] || continue

    case "$path" in
      AGENTS.md)
        fail "publication target tree excludes AGENTS.md"
        ;;
      dist/*)
        fail "publication target tree excludes dist/ paths"
        ;;
      .planning/*)
        allowed=false
        for allowed_path in "${ALLOWED_PLANNING_FILES[@]}"; do
          if [ "$path" = "$allowed_path" ]; then
            allowed=true
            break
          fi
        done
        if [ "$allowed" = true ]; then
          :
        else
          fail "publication target tree excludes private .planning path: $path"
        fi
        ;;
    esac

    case "$path" in
      *.dmg|*.dmg.sha256|*.manifest.json|*.iinaplgz|*.xcarchive|*.zip|*.tar|*.tar.gz|*.tgz|*.pkg)
        fail "publication target tree excludes generated release artifact: $path"
        ;;
    esac
  done <<< "$tree_paths"

  if ! printf '%s\n' "$tree_paths" | grep -Fxq "AGENTS.md"; then
    pass "publication target tree excludes AGENTS.md"
  fi

  if ! printf '%s\n' "$tree_paths" | grep -Eq '^dist/'; then
    pass "publication target tree excludes dist/ paths"
  fi

  pass "git ls-tree -r --name-only inspected full publication target tree"
}

